"""Convert NASA OSDR OSD-575 (Inspiration4) metabolic panel CSV into a TypeScript module.
Usage: python3 scripts/extract_i4.py <OSD-575_CMP.csv> src/data/inspiration4.ts
AI-assisted script (Claude). Values are copied unchanged from the NASA file."""
import csv, sys, json, re

rows = list(csv.DictReader(open(sys.argv[1], encoding="utf-8-sig")))
keys = {
    "glucose": ("Glucose (blood sugar)", "mg/dL"),
    "calcium": ("Calcium", "mg/dL"),
    "sodium": ("Sodium", "mmol/L"),
    "potassium": ("Potassium", "mmol/L"),
    "creatinine": ("Creatinine", "mg/dL"),
    "urea_nitrogen_bun": ("Urea nitrogen (BUN)", "mg/dL"),
    "albumin": ("Albumin", "g/dL"),
    "total_protein": ("Total protein", "g/dL"),
    "alkaline_phosphatase": ("Alkaline phosphatase", "U/L"),
    "carbon_dioxide": ("Bicarbonate (CO₂)", "mmol/L"),
    "chloride": ("Chloride", "mmol/L"),
    "globulin": ("Globulin", "g/dL"),
}
cols = list(rows[0].keys())


def col(prefix, kind):
    for c in cols:
        if not c.startswith(prefix + "_"):
            continue
        rest = c[len(prefix) + 1:]
        if kind == "value" and rest.startswith("value"):
            return c
        if kind == "min" and rest.startswith("range_min"):
            return c
        if kind == "max" and (rest.startswith("range_max") or rest.startswith("max")):
            return c
    return None


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


markers = {}
for k, (name, unit) in keys.items():
    mins = [num(r[col(k, "min")]) for r in rows if col(k, "min")]
    maxs = [num(r[col(k, "max")]) for r in rows if col(k, "max")]
    mins = [m for m in mins if m is not None]
    maxs = [m for m in maxs if m is not None]
    markers[k] = {"name": name, "unit": unit,
                  "min": min(mins) if mins else None, "max": max(maxs) if maxs else None}

samples = []
for r in rows:
    m = re.match(r"(C00\d)_serum_([LR])([+-]\d+)", r["Sample Name"])
    if not m:
        continue
    crew, ph, day = m.group(1), m.group(2), int(m.group(3))
    samples.append({"crew": crew, "label": ph + m.group(3), "day": day,
                    "phase": "pre" if ph == "L" else "post",
                    "values": {k: num(r[col(k, "value")]) for k in keys}})
samples.sort(key=lambda s: (s["crew"], s["day"]))

src = ("// REAL NASA DATA - NASA OSDR OSD-575 (SpaceX Inspiration4, Sept 2021)\n"
       "// File: LSDS-8_Comprehensive_Metabolic_Panel_CMP_TRANSFORMED.csv\n"
       "// https://osdr.nasa.gov/bio/repo/data/studies/OSD-575  (generated by scripts/extract_i4.py, values unchanged)\n"
       "export interface I4Sample { crew: string; label: string; day: number; phase: 'pre' | 'post'; values: Record<string, number | null> }\n"
       "export interface I4Marker { name: string; unit: string; min: number | null; max: number | null }\n"
       f"export const I4_MARKERS: Record<string, I4Marker> = {json.dumps(markers, indent=1, ensure_ascii=False)};\n"
       f"export const I4_SAMPLES: I4Sample[] = {json.dumps(samples)};\n")
open(sys.argv[2], "w").write(src)
for s in samples:
    print(s["crew"], s["label"], {k: s["values"][k] for k in ["glucose", "calcium", "creatinine", "sodium"]})
print(json.dumps(markers, ensure_ascii=False))
